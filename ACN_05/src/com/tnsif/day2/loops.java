package com.tnsif.day2;

public class loops {

	public static void main(String[] args) {
		for(int i=1; i<=10; i++ )
		{
			System.out.println(i);
		}
		System.out.println("\n");
		
		
		int num=20;
		int n = 1;
		while(n<num)
		{
			System.out.println(n);
			n++;
		}
		System.out.println("");
		
		int j=1;
		do {
			System.out.println(j);
			j++;
		}
		while(j<=10);
		System.out.println("");

	}

}
